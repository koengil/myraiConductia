// The synthetic Gmail twin (#259 phase 6, plan D10): a committed, generated
// replay of the fixture corpus in the shape Gmail answers, so the real Gmail
// ContentSource can run in CI, in the demo and for sibling workstreams with no
// trial and no credential. Offline: no network, no token, and it imports no
// reader (the fence lists scripts that do), so it is not fence-listed.
//
//   npm run google:build-twin [-- --seed <seed.jsonl>] [--out <dir>]
//   npm run discovery:build-demo-twin            (= --demo: the demo twin, below)
//
// It is a generator, not a recording. Every file says `synthetic: true`, and
// the hand-written responses (a 429 then 200, a 404 on a stale history start)
// carry `synthetic: true` themselves. The recorded replay (tests/fixtures/
// discovery/gmail, from the Oct 7 trial) is the evidence that the twin's shapes
// match Google's; the parity test holds them to the same answer.
//
// Phases mirror the mailbox's state, as the recorder's do (R15). Each is a
// complete mailbox, not a delta:
//   seeded        the first import; the one SPAM message sits in SPAM
//   after-imports the two `after-imports` messages have arrived
//   after-unspam  the SPAM message has been moved to the inbox
//
// Gmail ids are per mailbox and deterministic: sha256(mailbox|messageId)
// truncated to 16 hex characters, so two mailboxes' copies of one message get
// different message and thread ids (R18). The Graph conversationId is never
// used: threads group by the References root, as Gmail groups by headers.

export const DEFAULT_TWIN_DIR = join(process.cwd(), 'tests', 'fixtures', 'discovery', 'gmail-twin');
/** The demo Gmail twin: the mail the Graph demo serves (demo/graph*), in the shape Gmail answers. */
export const DEMO_TWIN_DIR = join(process.cwd(), 'tests', 'fixtures', 'discovery', 'demo', 'gmail-twin');
/** Generated by scripts/discovery/build-demo-corpus.ts (never appended by hand: it is rewritten); every line is read (TH3). */
export const DEMO_GMAIL_SEED = join(process.cwd(), 'tests', 'fixtures', 'discovery', 'demo', 'gmail-seed.jsonl');

/**
 * The demo twin's seed: the base fixture mail, then every line of demo/gmail-seed.jsonl. The base mail is
 * flattened to `seeded` with no labels, because demo/graph serves it verbatim: no Falcon late mail, no SPAM.
 * So the twin's `seeded` phase holds what demo/graph holds and `after-imports` what demo/graph-after-imports holds.
 */
export function demoGmailSeed(seedFile: string = DEMO_GMAIL_SEED): SeedMessage[] {
  const base = fixtureToSeed().map((m) => {
    const flat: SeedMessage = { ...m, phase: 'seeded' };
    delete flat.labels;
    return flat;
  });
  const demo = parseSeedJsonl(readFileSync(seedFile, 'utf8'));
  const seen = new Set(base.map((m) => m.messageId));
  for (const m of demo) {
    if (seen.has(m.messageId)) throw new Error(`demo Gmail seed: ${m.messageId} is in both the base and the demo mail`);
    seen.add(m.messageId);
  }
  return [...base, ...demo];
}

/**
 * The demo team inbox (#581 phase 12): a firm mailbox nobody signs in as, so the demo twin holds a replay for it
 * beside the three personas'. scripts/discovery/lib/corpusSelect.ts repeats the address (DEMO_TEAM_INBOX) for the
 * seed, which cannot import this module's neighbours; tests/discovery/demo-seed-selection.test.ts pins the two.
 */
export const DEMO_TEAM_MAILBOX = 'deals@bank.example';

/**
 * The demo mail the team inbox also holds, a copy of each (same Message-ID and content, so the pipeline reads one
 * item with two provenance rows and the extraction replies already cover it):
 *   Kestrel  004 is also in Morgan's mailbox (the shared message of the mixed candidate); 005 (teaser) and 015
 *            (LOI signed) are held by Storm alone, so they are team-only once Storm has no personal source
 *   Osprey   001, 004 and 007, which Morgan holds too
 *   noise    001 and 002, which route to no deal
 * Only seeded mail: the late mail (phase after-imports) is not the team inbox's story.
 */
export const DEMO_TEAM_MESSAGE_IDS: readonly string[] = [
  '<kestrel-004@bank.example>',
  '<kestrel-005@bank.example>',
  '<kestrel-015@bank.example>',
  '<osprey-001@bank.example>',
  '<osprey-004@bank.example>',
  '<osprey-007@bank.example>',
  '<noise-001@bank.example>',
  '<noise-002@bank.example>',
];

/** The demo seed with the team inbox added to the mailboxes that hold each of DEMO_TEAM_MESSAGE_IDS. Pure. */
export function withDemoTeamMailbox(messages: SeedMessage[]): SeedMessage[] {
  const wanted = new Set(DEMO_TEAM_MESSAGE_IDS);
  const out = messages.map((m) => (wanted.has(m.messageId) ? { ...m, mailboxes: [...m.mailboxes, DEMO_TEAM_MAILBOX] } : m));
  const held = out.filter((m) => m.mailboxes.includes(DEMO_TEAM_MAILBOX));
  if (held.length !== wanted.size || held.some((m) => (m.phase ?? 'seeded') !== 'seeded')) {
    throw new Error('demo team inbox: every listed message must be in the demo mail, seeded and not already in the team inbox');
  }
  return out;
}

/** What `--demo` writes: the demo mail, plus the team inbox's copies (the Graph demo fixtures have no team inbox). */
export function demoTwinSeed(seedFile: string = DEMO_GMAIL_SEED): SeedMessage[] {
  return withDemoTeamMailbox(demoGmailSeed(seedFile));
}

// The queries are the reader's own (src/lib/constants/googleReader.ts), so the twin cannot drift from them;
// tests/google/replay-coverage.test.ts fails if the reader asks for something the twin lacks. Every listing and
// metadata answer is masked the way the `fields` parameter masks it live: no snippet, size or payload tree.

export const TWIN_PHASES = ['seeded', 'after-imports', 'after-unspam'] as const;
/** A history start id no mailbox ever had: Gmail answers 404, and the reader must re-sync (phase 3). */
export const STALE_HISTORY_ID = '1';

const hex16 = (text: string): string => createHash('sha256').update(text).digest('hex').slice(0, 16);
const b64url = (bytes: Uint8Array): string => Buffer.from(bytes).toString('base64url');
const millis = (m: SeedMessage): number => Date.parse(m.date);
const rootOf = (m: SeedMessage): string => m.references?.[0] ?? m.inReplyTo ?? m.messageId;
/** The user labels a seed names (anything but SPAM), sorted: the twin's label ids follow this order. */
const userLabelsOf = (messages: SeedMessage[]): string[] =>
  [...new Set(messages.flatMap((m) => (m.labels ?? []).filter((l) => l !== 'SPAM')))].sort();
const formatAddress = ({ name, address }: SeedAddress): string => (name ? `"${name}" <${address}>` : address);

type State = { messages: SeedMessage[]; spam: Set<string> };

function stateOf(messages: SeedMessage[], phase: (typeof TWIN_PHASES)[number]): State {
  const held = phase === 'seeded' ? messages.filter((m) => (m.phase ?? 'seeded') === 'seeded') : messages;
  const spam = new Set(
    phase === 'after-unspam' ? [] : held.filter((m) => m.labels?.includes('SPAM')).map((m) => m.messageId),
  );
  return { messages: held, spam };
}

const ok = (body: unknown): ReplayResponse => ({ status: 200, body });

function replayFor(mailbox: string, all: SeedMessage[]): GmailReplay {
  const mine = all.filter((m) => m.mailboxes.map((a) => a.toLowerCase()).includes(mailbox));
  // User labels are mailbox-wide ids (Label_1, ...), in name order; a seed with none has no labels.list key.
  const userLabels = userLabelsOf(all);
  const labelIdOf = (name: string) => `Label_${userLabels.indexOf(name) + 1}`;
  const base = `https://gmail.googleapis.com/gmail/v1/users/${encodeURIComponent(mailbox)}`;
  const idOf = (m: SeedMessage) => hex16(`${mailbox}|${m.messageId}`);
  const threadIdOf = (m: SeedMessage) => hex16(`${mailbox}|thread|${rootOf(m)}`);

  const seededProfile = 1000 + mine.filter((m) => (m.phase ?? 'seeded') === 'seeded').length;
  const historyIds: Record<(typeof TWIN_PHASES)[number], number> = {
    seeded: seededProfile,
    'after-imports': seededProfile + mine.filter((m) => m.phase === 'after-imports').length,
    'after-unspam': seededProfile + mine.filter((m) => m.phase === 'after-imports').length + mine.filter((m) => m.labels?.includes('SPAM')).length,
  };

  const phases: GmailReplay['phases'] = {};
  for (const phase of TWIN_PHASES) {
    const { messages, spam } = stateOf(mine, phase);
    const labelsOf = (m: SeedMessage): string[] =>
      spam.has(m.messageId) ? ['SPAM'] : ['INBOX', ...(m.labels ?? []).filter((l) => l !== 'SPAM').map(labelIdOf)];
    const entries: Record<string, ReplayResponse[]> = {};
    const add = (url: string, ...responses: ReplayResponse[]) => {
      entries[replayKey('GET', url)] = responses;
    };
    const historyId = String(historyIds[phase]);

    add(`${base}/profile`, ok({ emailAddress: mailbox, messagesTotal: messages.length, threadsTotal: 0, historyId }));
    // The reader asks for the mailbox's label names once per pass when a label rule names a user label.
    if (userLabels.length > 0) {
      add(
        `${base}/labels?fields=${GMAIL_LABELS_FIELDS}`,
        ok({ labels: [{ id: 'INBOX', name: 'INBOX' }, { id: 'SPAM', name: 'SPAM' }, ...userLabels.map((name) => ({ id: labelIdOf(name), name }))] }),
      );
    }

    // Threads by the References root, newest first as Gmail lists them. A thread
    // holding only SPAM is not listed with includeSpamTrash=false.
    const threads = new Map<string, SeedMessage[]>();
    for (const m of messages) threads.set(threadIdOf(m), [...(threads.get(threadIdOf(m)) ?? []), m]);
    const ordered = [...threads.entries()]
      .map(([id, held]) => ({ id, held: [...held].sort((a, b) => millis(a) - millis(b) || a.messageId.localeCompare(b.messageId)) }))
      .sort((a, b) => millis(b.held[b.held.length - 1]) - millis(a.held[a.held.length - 1]) || a.id.localeCompare(b.id));
    const listed = ordered.filter(({ held }) => held.some((m) => !spam.has(m.messageId)));
    add(
      `${base}/threads?maxResults=100&includeSpamTrash=false&fields=${GMAIL_THREAD_LIST_FIELDS}`,
      ok({ threads: listed.map(({ id }) => ({ id, historyId })) }),
    );

    // The oldest message of a mailbox is throttled once (synthetic): the reader must back off and read on.
    const oldest = [...messages].sort((a, b) => millis(a) - millis(b) || a.messageId.localeCompare(b.messageId))[0];
    for (const { id, held } of ordered) {
      const metadataOf = (m: SeedMessage) => ({
        id: idOf(m),
        threadId: id,
        labelIds: labelsOf(m),
        internalDate: String(millis(m)),
        historyId,
        payload: { headers: metadataHeadersOf(m) },
        ...(m.classification ? { classificationLabelValues: m.classification } : {}),
      });
      add(`${base}/threads/${id}?${GMAIL_THREAD_METADATA_QUERY}`, ok({ id, historyId, messages: held.map(metadataOf) }));
      for (const m of held) {
        // The incremental pass reads each message's labels and time before its original.
        add(`${base}/messages/${idOf(m)}?${GMAIL_METADATA_QUERY}`, ok(metadataOf(m)));
        const raw = ok({
          id: idOf(m),
          threadId: id,
          labelIds: labelsOf(m),
          snippet: '',
          historyId,
          internalDate: String(millis(m)),
          sizeEstimate: 0,
          raw: b64url(buildRfc822(m)),
        });
        const throttled: ReplayResponse = {
          status: 429,
          synthetic: true,
          body: { error: { code: 429, message: 'Rate Limit Exceeded', errors: [{ reason: 'rateLimitExceeded' }], status: 'RESOURCE_EXHAUSTED' } },
        };
        add(`${base}/messages/${idOf(m)}?format=raw`, ...(m === oldest ? [throttled, raw] : [raw]));
      }
    }

    // history.list, from each id a reader of an earlier phase may hold (a mailbox
    // checkpointed at `seeded` polls from S, one at `after-imports` from I, one at
    // `after-unspam` from U), and from this phase's own id, which answers "nothing
    // new" so a repeated poll in one phase never misses. Records are sequential
    // (S+1 ... I are the imports, I+1 ... U the un-spams), and a poll from id N
    // answers the records after N, as Gmail does.
    const S = historyIds.seeded;
    const I = historyIds['after-imports'];
    const U = historyIds['after-unspam'];
    const importRecords = mine
      .filter((m) => m.phase === 'after-imports')
      .map((m, i) => ({
        id: String(S + i + 1),
        messagesAdded: [{ message: { id: idOf(m), threadId: threadIdOf(m), labelIds: labelsOf(m) } }],
      }));
    const unspamRecords = mine
      .filter((m) => m.labels?.includes('SPAM'))
      .map((m, j) => ({
        id: String(I + j + 1),
        labelsRemoved: [{ message: { id: idOf(m), threadId: threadIdOf(m), labelIds: ['INBOX'] }, labelIds: ['SPAM'] }],
      }));
    const records = phase === 'seeded' ? [] : phase === 'after-imports' ? importRecords : [...importRecords, ...unspamRecords];
    const current = historyIds[phase];
    const historyUrl = (start: number) =>
      `${base}/history?historyTypes=messageAdded&historyTypes=labelRemoved&maxResults=100&startHistoryId=${start}&fields=${GMAIL_HISTORY_FIELDS}`;
    for (const start of new Set([S, I, U].filter((n) => n <= current))) {
      const after = records.filter((r) => Number(r.id) > start);
      add(historyUrl(start), ok({ ...(after.length > 0 ? { history: after } : {}), historyId }));
    }
    // Synthetic, and in every phase: a start id Gmail no longer holds.
    add(
      `${base}/history?historyTypes=messageAdded&historyTypes=labelRemoved&maxResults=100&startHistoryId=${STALE_HISTORY_ID}&fields=${GMAIL_HISTORY_FIELDS}`,
      {
        status: 404,
        synthetic: true,
        body: { error: { code: 404, message: 'Requested entity was not found.', errors: [{ reason: 'notFound' }], status: 'NOT_FOUND' } },
      },
    );
    phases[phase] = entries;
  }

  return { format: GMAIL_REPLAY_FORMAT, mailbox, synthetic: true, phases };
}

function headersOf(m: SeedMessage): Array<{ name: string; value: string }> {
  const headers: Array<{ name: string; value: string }> = [
    { name: 'From', value: formatAddress(m.from) },
    { name: 'To', value: m.to.map(formatAddress).join(', ') },
  ];
  if (m.cc.length > 0) headers.push({ name: 'Cc', value: m.cc.map(formatAddress).join(', ') });
  headers.push(
    { name: 'Subject', value: m.subject },
    { name: 'Date', value: new Date(m.date).toUTCString().replace('GMT', '+0000') },
    { name: 'Message-ID', value: m.messageId },
  );
  if (m.inReplyTo) headers.push({ name: 'In-Reply-To', value: m.inReplyTo });
  if (m.references && m.references.length > 0) headers.push({ name: 'References', value: m.references.join(' ') });
  for (const [name, value] of Object.entries(m.headers ?? {})) headers.push({ name, value });
  return headers;
}

/** A metadata answer holds only the headers the reader asks for, as Gmail's metadataHeaders does (#337). */
const METADATA_HEADER_NAMES = new Set<string>(GMAIL_METADATA_HEADERS.map((h) => h.toLowerCase()));
const metadataHeadersOf = (m: SeedMessage) => headersOf(m).filter((h) => METADATA_HEADER_NAMES.has(h.name.toLowerCase()));

/** One replay per mailbox that holds any of the messages, in address order. Pure and deterministic. */
export function buildGmailTwin(messages: SeedMessage[]): GmailReplay[] {
  const mailboxes = [...new Set(messages.flatMap((m) => m.mailboxes.map((a) => a.toLowerCase())))].sort();
  return mailboxes.map((mailbox) => replayFor(mailbox, messages));
}

export function twinFileName(mailbox: string): string {
  return `${mailbox}.replay.json`;
}

function main(): void {
  const demo = process.argv.includes('--demo');
  const seedFile = argValue(process.argv, '--seed');
  if (demo && seedFile) throw new Error('--demo composes its own seed; drop --seed');
  const out = resolve(argValue(process.argv, '--out') ?? (demo ? DEMO_TWIN_DIR : DEFAULT_TWIN_DIR));
  const messages = demo ? demoTwinSeed() : seedFile ? parseSeedJsonl(readFileSync(seedFile, 'utf8')) : fixtureToSeed();
  mkdirSync(out, { recursive: true });
  for (const replay of buildGmailTwin(messages)) {
    writeFileSync(join(out, twinFileName(replay.mailbox)), `${JSON.stringify(replay, null, 2)}\n`);
    console.log(`wrote ${twinFileName(replay.mailbox)}`);
  }
}

if (process.argv[1]?.endsWith('build-gmail-twin.ts')) {
  try {
    main();
  } catch (error) {
    console.error(`❌ ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
