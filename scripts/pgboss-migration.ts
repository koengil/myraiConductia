import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Generates supabase/migrations/20260925140000_pgboss_schema.sql from the
// construction plan of the pinned pg-boss (design Q2): the queue schema is
// reviewed like any migration, and the worker runs with migrate: false.
//
//   node --import tsx scripts/pgboss-migration.ts            # write the file
//   node --import tsx scripts/pgboss-migration.ts --check    # fail if it drifted
//
// tests/pgboss-migration.test.ts runs the check, so bumping pg-boss without
// a matching migration turns the unit suite red. A version bump needs a NEW
// migration built from getMigrationPlans(schema, fromVersion), never an edit
// to this one.
//
// The plan is pg-boss's verbatim, less its own transaction wrapper (BEGIN,
// SET LOCAL timeouts, COMMIT): production applies each migration with
// `psql --single-transaction`, and an inner COMMIT would end that transaction
// early. The plan runs inside a guard, so replaying the file over a database
// that already holds the schema changes nothing.

export const PGBOSS_SCHEMA = 'pgboss';
export const PGBOSS_MIGRATION = join('supabase', 'migrations', '20260925140000_pgboss_schema.sql');

const WRAPPER_LINE = /^\s*(BEGIN;|COMMIT;|SET LOCAL [^;]+;)\s*$/;

export function stripTransactionWrapper(plan: string): string {
  return plan
    .split('\n')
    .filter((line) => !WRAPPER_LINE.test(line))
    .join('\n')
    .trim();
}

export function pgbossMigrationSql(plan: string, version: string): string {
  const body = stripTransactionWrapper(plan);
  if (body.includes('$pgboss_plan$')) throw new Error('The pg-boss plan contains the wrapper quote tag');
  return `-- supabase/migrations/20260925140000_pgboss_schema.sql
-- GENERATED by scripts/pgboss-migration.ts from pg-boss ${version}'s
-- construction plan (getConstructionPlans('${PGBOSS_SCHEMA}')). Do not edit by hand:
-- regenerate, and tests/pgboss-migration.test.ts checks the two agree.
--
-- The discovery workers' job queue (deal-discovery phase 4, design Q2). The
-- worker runs pg-boss with migrate: false and createSchema: false, so its
-- database role needs no DDL, and upgrading pg-boss is a new, reviewed
-- migration built from getMigrationPlans().
--
-- The schema lives outside public: the Data API never exposes it, and the
-- schema snapshot and preflight (public only) do not track it. Nothing but
-- the table owner and the worker's connection reaches it; see the grants at
-- the end.

do $pgboss_install$
begin
  if to_regclass('${PGBOSS_SCHEMA}.version') is not null then
    raise notice 'pgboss schema already installed; nothing to do';
    return;
  end if;
  execute $pgboss_plan$
${body}
$pgboss_plan$;
end
$pgboss_install$;

-- The API roles never reach the queue: job payloads name tenants and sources.
revoke all on schema ${PGBOSS_SCHEMA} from public, anon, authenticated;
revoke all on all tables in schema ${PGBOSS_SCHEMA} from public, anon, authenticated;
revoke all on all functions in schema ${PGBOSS_SCHEMA} from public, anon, authenticated;
revoke all on all sequences in schema ${PGBOSS_SCHEMA} from public, anon, authenticated;
`;
}

async function generated(): Promise<string> {
  const { getConstructionPlans } = await import('pg-boss');
  const { version } = JSON.parse(readFileSync(join(process.cwd(), 'node_modules', 'pg-boss', 'package.json'), 'utf8')) as {
    version: string;
  };
  return pgbossMigrationSql(getConstructionPlans(PGBOSS_SCHEMA), version);
}

export async function migrationIsCurrent(): Promise<boolean> {
  return readFileSync(join(process.cwd(), PGBOSS_MIGRATION), 'utf8') === (await generated());
}

async function main(argv: string[]): Promise<void> {
  if (argv.includes('--check')) {
    if (!(await migrationIsCurrent())) {
      console.error(`${PGBOSS_MIGRATION} does not match the installed pg-boss. Add a migration for the new version.`);
      process.exit(1);
    }
    console.log(`${PGBOSS_MIGRATION} matches the installed pg-boss.`);
    return;
  }
  writeFileSync(join(process.cwd(), PGBOSS_MIGRATION), await generated());
  console.log(`Wrote ${PGBOSS_MIGRATION}.`);
}

if (process.argv[1]?.endsWith('pgboss-migration.ts')) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
