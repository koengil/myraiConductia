// Risk repository, first slice (Oct 20; Storm, Oct 19 build sync): 100 twin pairs of
// fictional sell-side banker mail. Each pair is one risky email and a clean twin that
// uses the same vocabulary innocently, so the screen is measured on the line between
// them, not on obvious cases alone. The patterns come from the TYPES of conduct seen in
// SEC and FINRA enforcement actions, investment-bank litigation and negative press;
// no real case, firm or person is named. Every company, person and project is invented.
//
// risk:       legal | regulatory | compliance | reputational (the pair shares one).
// difficulty: obvious, or edge (borderline wording; for a clean twin, risky-sounding
//             words in an innocent email). Most pairs are edge on purpose.
//
// Ids: each pair declares its own id, repo-NNN; repo-NNNf is the risky email (expected
// flag), repo-NNNc its clean twin. The id is written in the data, not derived from the
// position, so inserting or removing a pair never renumbers the others and a recorded
// result keeps pointing at the same case. A new pair takes the next unused number.
//
// Today's rule layer looks only for promissory and MNPI wording, so most of these
// families have no rule at all; the slice records that gap rather than hiding it.
//
// Labels: which email should flag and which should clear is engineering judgment,
// pending review by the CCO (Chief Compliance Officer). The tests pin these labels so a
// change is deliberate, but pinning does not make them ground truth.
