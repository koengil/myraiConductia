// The offline replies of the demo-only deal proposal step (#460), built from the
// test double's table (proposeReplyTable.ts) and written to:
//
//   tests/fixtures/discovery/demo/model-replies/propose.v2.stub.json
//
// It is NOT a model output. Like extract.v1.stub.json (stubReplies.ts), it is
// keyed by the content hash normalizeMessage gives each message, so the worker's
// recorded transport hits it on the demo corpus. It covers every message the
// firm rules can leave unrouted in any read order: those with no "Project <Name>"
// codename of their own, before aliases and thread continuation, which depend on
// what was read first. Delete with the step when #459 lands.
//
//   node --import tsx tests/helpers/proposeStubReplies.ts            write the stub
//   node --import tsx tests/helpers/proposeStubReplies.ts --check    list drift, exit 1

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

import { demoPipeline } from '../../scripts/discovery/lib/demoPipeline';
import type { DedupedItem } from '@/lib/discovery/normalize';
import { PROPOSAL_MODEL } from '@/lib/discovery/propose/model';
import { parseProposalReply } from '@/lib/discovery/propose/parse';
import { routeByFirmRules } from '@/lib/discovery/route/firmRules';
import { PROMPT_HASH, PROMPT_VERSION } from '@/lib/modelGateway/prompts/dealProposal.v2';
import { recordingDigest, type RecordingFile } from '@/lib/modelGateway/record';
import { SYNTHETIC_CORPUS_DIGEST, SYNTHETIC_MESSAGE_IDS } from '@/lib/modelGateway/syntheticCorpus.generated';

import { PROPOSE_REPLY_TABLE } from './proposeReplyTable';

// Not imported from ./stubReplies: its run-as-script check (argv[1] ends with
// 'stubReplies.ts') also matches this file's name, so importing it would run it.
const REPLIES_DIR = 'tests/fixtures/discovery/demo/model-replies';
const LATE_DIR = 'tests/fixtures/discovery/demo/graph-after-imports';
export const PROPOSE_STUB_PATH = `${REPLIES_DIR}/propose.v2.stub.json`;

export const PROPOSE_STUB_PROVENANCE =
  'STUB, not a model recording. Generated by tests/helpers/proposeStubReplies.ts from tests/helpers/proposeReplyTable.ts ' +
  '(the offline test double of the demo-only deal proposal step, #460). ' +
  'Regenerate with: node --import tsx tests/helpers/proposeStubReplies.ts';

/** Demo corpus messages the firm rules can leave unrouted: no codename of their own. */
export function proposableItems(root: string = process.cwd()): DedupedItem[] {
  return demoPipeline(join(root, LATE_DIR)).items.filter(
    (entry) => entry.item.kind !== 'document' && routeByFirmRules([entry], { scope: 'unscoped' })[0].routes.length === 0,
  );
}

export function buildProposeStub(root: string = process.cwd()): RecordingFile {
  const items = proposableItems(root);
  const known = new Set(items.map((e) => e.item.internetMessageId));
  const unknown = Object.keys(PROPOSE_REPLY_TABLE).filter((id) => !known.has(id));
  if (unknown.length) throw new Error(`proposeReplyTable names mail the firm rules route: ${unknown.join(', ')}`);

  const replies: RecordingFile['replies'] = {};
  for (const { item } of items) {
    const id = item.internetMessageId;
    const reply = PROPOSE_REPLY_TABLE[id];
    if (!reply) throw new Error(`${id}: proposeReplyTable has no reply for this unrouted message`);
    if (!SYNTHETIC_MESSAGE_IDS.has(id)) throw new Error(`${id}: not in the synthetic corpus`);
    const text = JSON.stringify(reply);
    if (!parseProposalReply(text, []).ok) throw new Error(`${id}: the double's reply does not parse`);
    replies[item.contentHash] = { text, responseId: `msg_stub_propose_${item.contentHash.slice(0, 12)}` };
  }
  return {
    format: 'conductia.model-replies/v1',
    purpose: 'deal_proposal',
    promptVersion: PROMPT_VERSION,
    promptHash: PROMPT_HASH,
    model: PROPOSAL_MODEL,
    provider: 'stub',
    upstreamModel: 'stub',
    provenance: PROPOSE_STUB_PROVENANCE,
    recordedAt: 'never: generated, not recorded',
    corpusDigest: SYNTHETIC_CORPUS_DIGEST,
    replies,
    digest: recordingDigest(replies),
  };
}

export const serializeProposeStub = (file: RecordingFile): string => `${JSON.stringify(file, null, 2)}\n`;

function main(): void {
  const root = process.cwd();
  const wanted = serializeProposeStub(buildProposeStub(root));
  const target = join(root, PROPOSE_STUB_PATH);
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === wanted) {
      console.log(`${PROPOSE_STUB_PATH} is current`);
      return;
    }
    console.error(
      `${PROPOSE_STUB_PATH} ${current === null ? 'is missing' : 'differs'}; run: node --import tsx tests/helpers/proposeStubReplies.ts`,
    );
    process.exit(1);
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, wanted);
  console.log(`wrote ${PROPOSE_STUB_PATH}`);
}

if (process.argv[1]?.endsWith('/proposeStubReplies.ts') || process.argv[1] === 'proposeStubReplies.ts') main();
