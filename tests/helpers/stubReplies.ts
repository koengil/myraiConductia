// The offline stand-in for the owner's recording (T2) while it is absent.
//
// It is built from the test double's table (demoReplyTable.ts), one reply per
// item the recorder would cover, and written to a path of its own:
//
//   tests/fixtures/discovery/demo/model-replies/extract.v1.stub.json
//
// It is NOT a model output and it never takes the place of
// model-replies/extract.v1.json, which only the owner-run recorder writes. The
// journey, CI and the runbook use the recording when that file exists and fall
// back to this stub otherwise (see e2e/support/recording.ts). The stub lives
// under tests/ because production code may not import tests/ (the reader fence).
//
//   node --import tsx tests/helpers/stubReplies.ts            write the stub
//   node --import tsx tests/helpers/stubReplies.ts --check    list drift, exit 1

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

import { recordableItems } from '../../scripts/discovery/lib/demoPipeline';
import { parseMilestoneReply } from '@/lib/discovery/extract/parse';
import { DEFAULT_EXTRACT_MODEL } from '@/lib/modelGateway/processorGate';
import { PROMPT_HASH, PROMPT_VERSION } from '@/lib/modelGateway/prompts/milestoneExtract.v1';
import { recordingDigest, type RecordingFile } from '@/lib/modelGateway/record';
import { SYNTHETIC_CORPUS_DIGEST } from '@/lib/modelGateway/syntheticCorpus.generated';

import { DEMO_REPLY_TABLE } from './demoReplyTable';
import { replyText } from './modelReplyDouble';

export const REPLIES_DIR = 'tests/fixtures/discovery/demo/model-replies';
export const RECORDING_PATH = `${REPLIES_DIR}/extract.v1.json`;
export const STUB_PATH = `${REPLIES_DIR}/extract.v1.stub.json`;
export const LATE_DIR = 'tests/fixtures/discovery/demo/graph-after-imports';

export const STUB_PROVENANCE =
  'STUB, not a model recording. Generated by tests/helpers/stubReplies.ts from tests/helpers/demoReplyTable.ts ' +
  '(the offline test double). It stands in for extract.v1.json until the owner records it (T2). ' +
  'Regenerate with: node --import tsx tests/helpers/stubReplies.ts';

/** The stub for the corpus as it stands: a reply for every item the recorder would cover. */
export function buildStubRecording(root: string = process.cwd()): RecordingFile {
  const items = recordableItems(join(root, LATE_DIR));
  const known = new Set(items.map((i) => i.item.internetMessageId));
  const unknown = Object.keys(DEMO_REPLY_TABLE).filter((id) => !known.has(id));
  if (unknown.length) throw new Error(`demoReplyTable names mail the corpus does not select: ${unknown.join(', ')}`);

  const replies: RecordingFile['replies'] = {};
  for (const { item } of items) {
    const text = replyText(DEMO_REPLY_TABLE[item.internetMessageId] ?? []);
    const parsed = parseMilestoneReply(text, item.bodyText);
    if (!parsed.ok) throw new Error(`${item.internetMessageId}: the double's reply does not parse against its body (${parsed.error})`);
    replies[item.contentHash] = { text, responseId: `msg_stub_${item.contentHash.slice(0, 12)}` };
  }
  return {
    format: 'conductia.model-replies/v1',
    purpose: 'milestone_extract',
    promptVersion: PROMPT_VERSION,
    promptHash: PROMPT_HASH,
    model: DEFAULT_EXTRACT_MODEL,
    provider: 'stub',
    upstreamModel: 'stub',
    provenance: STUB_PROVENANCE,
    recordedAt: 'never: generated, not recorded',
    corpusDigest: SYNTHETIC_CORPUS_DIGEST,
    replies,
    digest: recordingDigest(replies),
  };
}

export const serializeStub = (file: RecordingFile): string => `${JSON.stringify(file, null, 2)}\n`;

/** The replies file the run should use: the owner's recording when it exists, else the stub. */
export function repliesPath(root: string = process.cwd()): { path: string; kind: 'recording' | 'stub' } {
  return existsSync(join(root, RECORDING_PATH))
    ? { path: RECORDING_PATH, kind: 'recording' }
    : { path: STUB_PATH, kind: 'stub' };
}

function main(): void {
  const root = process.cwd();
  const wanted = serializeStub(buildStubRecording(root));
  const target = join(root, STUB_PATH);
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === wanted) {
      console.log(`${STUB_PATH} is current`);
      return;
    }
    console.error(`${STUB_PATH} ${current === null ? 'is missing' : 'differs'}; run: node --import tsx tests/helpers/stubReplies.ts`);
    process.exit(1);
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, wanted);
  console.log(`wrote ${STUB_PATH}`);
}

if (process.argv[1]?.endsWith('stubReplies.ts')) main();
